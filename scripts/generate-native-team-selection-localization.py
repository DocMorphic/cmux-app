#!/usr/bin/env python3
"""Extract the pinned team-picker footer and failure translations without inventing copy."""
import argparse,hashlib,importlib.util,json,pathlib,subprocess
ROOT=pathlib.Path(__file__).resolve().parents[1]
PIN='a5911a1f92f3eeb11c4d7f3e2ef89204718c5009';CATALOG='ios/cmux/Resources/Localizable.xcstrings'
p=argparse.ArgumentParser();p.add_argument('--upstream',type=pathlib.Path,required=True);p.add_argument('--out',type=pathlib.Path,default=ROOT);p.add_argument('--check',action='store_true');a=p.parse_args()
spec=importlib.util.spec_from_file_location('cmux_localization',ROOT/'scripts/mobile-ui-localization.py');module=importlib.util.module_from_spec(spec);spec.loader.exec_module(module)
raw=subprocess.check_output(['git','-C',str(a.upstream),'show',PIN+':'+CATALOG]);source=json.loads(raw)['strings'];rows=[]
for key,name in [('mobile.settings.teamFooter','cmux_team_selection_footer'),('mobile.settings.teamSwitchFailed','cmux_team_selection_failed')]:
 rows.append(dict(key=key,resource=name,translations={lang:source[key]['localizations'][lang]['stringUnit']['value'] for lang in module.LANGUAGES}))
data=dict(version=1,upstream=PIN,catalog=dict(path=CATALOG,sha256=hashlib.sha256(raw).hexdigest()),strings=rows)
outputs={pathlib.Path('third_party/cmux-localization/team-selection-strings.json'):(json.dumps(data,ensure_ascii=False,indent=2)+'\n').encode()}
for lang in module.LANGUAGES:
 folder=module.FOLDERS.get(lang,'values-'+lang)
 value=module.resource_xml(rows,lang,'from pinned team-picker labels').replace(b'Generated by scripts/mobile-ui-localization.py',b'Generated by scripts/generate-native-team-selection-localization.py')
 outputs[pathlib.Path('app/src/main/res')/folder/'cmux_team_selection_strings.xml']=value
for path,value in outputs.items():
 target=a.out/path
 if a.check:assert target.read_bytes()==value,str(target)
 else:target.parent.mkdir(parents=True,exist_ok=True);target.write_bytes(value)
print(('Checked' if a.check else 'Generated'),'two pinned labels in',len(module.LANGUAGES),'locales')
